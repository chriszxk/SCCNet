class GreyRelationalAttention(nn.Module):
    """
    Differentiable grey relational channel-spatial attention.

    rho:
        Distinguishing coefficient of grey relational analysis.
    pool_size:
        Spatial size used to calculate grey relations.
    """

    def __init__(
        self,
        rho: float = 0.5,
        pool_size: int = 32,
        eps: float = 1e-6,
    ):
        super().__init__()

        assert 0.0 < rho <= 1.0

        self.rho = rho
        self.pool_size = pool_size
        self.eps = eps

        # sigmoid(0) = 0.5:
        # equally combine mean and maximum reference sequences
        self.reference_mix = nn.Parameter(torch.zeros(1))

        self.channel_scale = nn.Parameter(torch.ones(1))
        self.spatial_scale = nn.Parameter(torch.ones(1))

        # Initial output is identical to the original A2C2f
        self.gamma = nn.Parameter(torch.zeros(1))

    @staticmethod
    def _standardize(x, dims, eps):
        mean = x.mean(dim=dims, keepdim=True)
        var = (x - mean).square().mean(dim=dims, keepdim=True)

        return (x - mean) * torch.rsqrt(var + eps)

    def forward(self, x):
        input_dtype = x.dtype
        _, _, h, w = x.shape

        # GRA reductions are calculated in FP32 for numerical stability
        feature = x.float()

        # Normalize each channel
        feature = self._standardize(
            feature,
            dims=(2, 3),
            eps=self.eps,
        )

        # Reduce computational cost while retaining strong small-object responses
        ph = min(h, self.pool_size)
        pw = min(w, self.pool_size)

        avg_feature = F.adaptive_avg_pool2d(feature, (ph, pw))
        max_feature = F.adaptive_max_pool2d(feature, (ph, pw))

        feature = 0.5 * (avg_feature + max_feature)

        # Adaptive reference sequence
        mix = torch.sigmoid(self.reference_mix)

        mean_reference = feature.mean(dim=1, keepdim=True)
        max_reference = feature.amax(dim=1, keepdim=True)

        reference = (
            (1.0 - mix) * mean_reference
            + mix * max_reference
        )

        # Absolute difference sequence
        delta = torch.abs(feature - reference)

        # Global extrema are treated as constants to improve stability
        delta_min = delta.amin(
            dim=(1, 2, 3),
            keepdim=True,
        ).detach()

        delta_max = delta.amax(
            dim=(1, 2, 3),
            keepdim=True,
        ).detach()

        # Grey relational coefficient
        coefficient = (
            delta_min + self.rho * delta_max
        ) / (
            delta + self.rho * delta_max + self.eps
        )

        # Grey relational grade
        channel_grade = coefficient.mean(
            dim=(2, 3),
            keepdim=True,
        )

        spatial_grade = coefficient.mean(
            dim=1,
            keepdim=True,
        )

        # Increase relative discrimination
        channel_grade = self._standardize(
            channel_grade,
            dims=(1,),
            eps=self.eps,
        )

        spatial_grade = self._standardize(
            spatial_grade,
            dims=(2, 3),
            eps=self.eps,
        )

        channel_scale = F.softplus(self.channel_scale)
        spatial_scale = F.softplus(self.spatial_scale)

        channel_weight = torch.sigmoid(
            channel_scale * channel_grade
        )

        spatial_weight = torch.sigmoid(
            spatial_scale * spatial_grade
        )

        spatial_weight = F.interpolate(
            spatial_weight,
            size=(h, w),
            mode="bilinear",
            align_corners=False,
        )

        # Center the modulation around zero
        modulation = (
            channel_weight - 0.5
        ) + (
            spatial_weight - 0.5
        )

        modulation = modulation.to(dtype=input_dtype)

        # Bounded residual scaling prevents feature explosion
        gamma = 0.5 * torch.tanh(self.gamma)
        gamma = gamma.to(dtype=input_dtype)

        return x * (1.0 + gamma * modulation)



class MHC_TransformerBlock(nn.Module):

    def __init__(self, c1: int, c2: int, num_heads: int):
        super().__init__()
        self.conv = None
        if c1 != c2:
            self.conv = Conv(c1, c2)
        self.linear = nn.Linear(c2, c2)  # learnable position embedding
        self.tr = MHCTransformerBlock(c2,num_heads)
        self.c2 = c2

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if self.conv is not None:
            x = self.conv(x)
        b, _, w, h = x.shape
        p = x.flatten(2).permute(2, 0, 1)
        return self.tr(p + self.linear(p)).permute(1, 2, 0).reshape(b, self.c2, w, h)


class h_sigmoid(nn.Module):
    def __init__(self, inplace=True):
        super(h_sigmoid, self).__init__()
        self.relu = nn.ReLU6(inplace=inplace)

    def forward(self, x):
        return self.relu(x + 3) / 6

class h_swish(nn.Module):
    def __init__(self, inplace=True):
        super(h_swish, self).__init__()
        self.sigmoid = h_sigmoid(inplace=inplace)

    def forward(self, x):
        return x * self.sigmoid(x)


